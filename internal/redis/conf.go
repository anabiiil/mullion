package redis

import (
	"strconv"
	"strings"
)

// Dev defaults for Mullion's Redis (see RenderConfig).
const (
	// MaxMemoryMB caps the dataset so a runaway job can't eat the
	// laptop's RAM.
	MaxMemoryMB = 512
	// Databases is Redis's own default (db0..db15).
	Databases = 16
)

// ConfOptions is what redis.conf is rendered from.
type ConfOptions struct {
	Port int
	// Password is requirepass ("" = none: a loopback-only dev server,
	// so frameworks' REDIS_PASSWORD=null just works).
	Password string
}

// RenderConfig writes Mullion's redis.conf. Every path in it is
// relative: the server is started with its working directory set to
// the Redis folder, which keeps the file valid on Windows too, where the
// MSYS2 build of redis-server can't read native C:\ paths.
//
// Choices, all for local development:
//   - bind 127.0.0.1 only, no password, protected mode on (which lets
//     loopback clients in without one);
//   - persistence by RDB snapshots (dump.rdb in data/) — taken within
//     5 minutes of any write and on every clean shutdown — and no AOF:
//     cache/session/queue data in dev doesn't need per-write
//     durability, and a single dump.rdb is trivial to back up and
//     restore;
//   - maxmemory 512mb with noeviction: past the cap writes fail loudly
//     ("OOM command not allowed") instead of Redis silently dropping
//     keys — evicting would quietly lose queued jobs and sessions, which
//     is far more confusing while developing;
//   - set-proc-title no, so `ps` still shows the binary's path (that is
//     how Mullion recognizes its own server);
//   - logs go to stdout (Mullion redirects them to logs/redis.log) and
//     Mullion keeps the pid file itself.
func RenderConfig(o ConfOptions) string {
	if o.Port <= 0 {
		o.Port = DefaultPort
	}
	lines := []string{
		"# Generated by Mullion — rewritten on every start; changes here are lost.",
		"# Use `mullion ports` to move the port.",
		"bind 127.0.0.1",
		"protected-mode yes",
		"port " + strconv.Itoa(o.Port),
		"tcp-keepalive 300",
		"daemonize no",
		// Keep the process title: a rewritten one ("redis-server
		// 127.0.0.1:6379") hides the executable path Mullion uses to
		// tell its own server from someone else's.
		"set-proc-title no",
		`logfile ""`,
		"loglevel notice",
		"databases " + strconv.Itoa(Databases),
		"dir data",
		"dbfilename dump.rdb",
		"save 300 1 60 1000",
		"stop-writes-on-bgsave-error no",
		"rdbcompression yes",
		"appendonly no",
		"maxmemory " + strconv.Itoa(MaxMemoryMB) + "mb",
		"maxmemory-policy noeviction",
		"lazyfree-lazy-user-flush yes",
	}
	if o.Password != "" {
		lines = append(lines, "requirepass "+quoteConf(o.Password))
	}
	return strings.Join(lines, "\n") + "\n"
}

// quoteConf double-quotes a redis.conf argument.
func quoteConf(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`)
	return `"` + r.Replace(s) + `"`
}
