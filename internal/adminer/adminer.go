// Package adminer installs Adminer — a single-file PHP database UI — into
// ~/.mullion/adminer, served by Mullion's PHP as https://adminer.<tld>.
// Mullion offers it as SQL Server's admin tool (it also speaks MySQL and
// PostgreSQL). It does not import app: app links the site (see
// app.EnsureAdminer), so this package stays free of import cycles.
package adminer

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"time"

	"pm/internal/download"
	"pm/internal/pmdir"
)

// SiteName is the site Adminer is linked as (adminer.<tld>).
const SiteName = "adminer"

// releasesAPI is GitHub's "latest release" endpoint for Adminer's
// official repository (https://github.com/vrana/adminer/releases); a
// variable so tests can point it at an httptest server.
var releasesAPI = "https://api.github.com/repos/vrana/adminer/releases/latest"

// downloadFile is a seam for tests.
var downloadFile = download.ToFile

var httpClient = &http.Client{Timeout: 30 * time.Second}

// Dir is where Adminer lives.
func Dir(paths pmdir.Paths) string { return paths.AdminerDir() }

// Installed reports whether Adminer's files are present.
func Installed(paths pmdir.Paths) bool {
	_, err := os.Stat(filepath.Join(Dir(paths), "adminer.php"))
	return err == nil
}

// Remove deletes Mullion's Adminer. Unlinking the site is the caller's.
func Remove(paths pmdir.Paths) error { return os.RemoveAll(Dir(paths)) }

type release struct {
	TagName string  `json:"tag_name"`
	Assets  []asset `json:"assets"`
}

type asset struct {
	Name string `json:"name"`
	URL  string `json:"browser_download_url"`
}

// fullBuildRe matches the all-drivers, all-languages build:
// adminer-<version>.php — not adminer-<v>-en.php (English only),
// adminer-<v>-mysql*.php (MySQL only) or editor-<v>.php.
var fullBuildRe = regexp.MustCompile(`^adminer-(\d+(?:\.\d+)*)\.php$`)

// pickAsset chooses the full Adminer build from a release's assets.
func pickAsset(assets []asset) (asset, string, error) {
	for _, a := range assets {
		if m := fullBuildRe.FindStringSubmatch(a.Name); m != nil {
			return a, m[1], nil
		}
	}
	names := make([]string, 0, len(assets))
	for _, a := range assets {
		names = append(names, a.Name)
	}
	return asset{}, "", fmt.Errorf("the latest Adminer release has no adminer-<version>.php (assets: %s)", strings.Join(names, ", "))
}

func latest(ctx context.Context) (asset, string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, releasesAPI, nil)
	if err != nil {
		return asset{}, "", err
	}
	req.Header.Set("Accept", "application/vnd.github+json")
	resp, err := httpClient.Do(req)
	if err != nil {
		return asset{}, "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return asset{}, "", fmt.Errorf("looking up the latest Adminer release: HTTP %s", resp.Status)
	}
	var rel release
	if err := json.NewDecoder(resp.Body).Decode(&rel); err != nil {
		return asset{}, "", fmt.Errorf("reading the Adminer release list: %w", err)
	}
	return pickAsset(rel.Assets)
}

// Install downloads the newest Adminer (a no-op when already installed)
// and writes its index.php wrapper. Returns the installed version ("" if
// it was already there).
func Install(ctx context.Context, paths pmdir.Paths) (string, error) {
	dir := Dir(paths)
	if Installed(paths) {
		return "", writeIndex(dir)
	}
	a, version, err := latest(ctx)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	fmt.Println("Downloading Adminer " + version + "...")
	if err := downloadFile(ctx, a.URL, filepath.Join(dir, "adminer.php")); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(dir, "VERSION"), []byte(version+"\n"), 0o644); err != nil {
		return "", err
	}
	return version, writeIndex(dir)
}

// Version reads the installed version ("" when unknown).
func Version(paths pmdir.Paths) string {
	b, err := os.ReadFile(filepath.Join(Dir(paths), "VERSION"))
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(b))
}

// indexPHP customizes Adminer the documented way
// (https://www.adminer.org/en/extension/: define adminer_object()
// returning a subclass of Adminer\Adminer, then include adminer.php).
// For MS SQL it trusts the server's self-signed certificate — the
// Microsoft drivers (ODBC 18) encrypt by default and would otherwise
// refuse a local SQL Server. Other drivers are untouched.
const indexPHP = `<?php
// Generated by mullion — recreated on install; put changes elsewhere.
function adminer_object() {
	class MullionAdminer extends Adminer\Adminer {
		function name(): string {
			return 'Adminer <small>(Mullion)</small>';
		}
		function connectSsl() {
			if (Adminer\DRIVER == 'mssql') {
				return array('TrustServerCertificate' => true);
			}
			return parent::connectSsl();
		}
	}
	return new MullionAdminer;
}
include __DIR__ . '/adminer.php';
`

func writeIndex(dir string) error {
	return os.WriteFile(filepath.Join(dir, "index.php"), []byte(indexPHP), 0o644)
}

// URL is Adminer's address with the SQL Server login form prefilled:
// Adminer reads the driver and server from the query (?mssql=<server>)
// and the user name from &username=.
func URL(tld string, port int) string {
	return "https://" + SiteName + "." + tld + "/?mssql=" + url.QueryEscape("127.0.0.1:"+strconv.Itoa(port)) + "&username=sa"
}
