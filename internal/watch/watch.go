// Package watch is the project page's live watcher (the Watch tab and
// `mullion watch`): what a site does while it is used — requests from
// Caddy's access log, Laravel's log files, and (with Mullion's PHP
// prepend loaded for that site) dumps, queries, jobs, cache, events,
// views, HTTP calls and a per-request timeline.
//
// Everything stays local. The PHP side (php/*.php, embedded here and
// written to <home>/watch/) appends JSON lines to
// <home>/watch/<site>/events.jsonl; this package tails that file and
// the logs, and turns lines into Items the panel streams.
package watch

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"os"
	"path/filepath"

	"pm/internal/config"
	"pm/internal/pmdir"
)

//go:embed php/mullion-watch.php
var gatePHP []byte

//go:embed php/mullion-watch-lib.php
var libPHP []byte

// Defaults for a site's thresholds (config.Watch fields left 0).
const (
	DefaultSlowRequestMs = 500
	DefaultSlowQueryMs   = 100
	DefaultNPlusOne      = 5
)

// Settings is a site's watcher configuration with defaults filled in.
type Settings struct {
	Enabled       bool   `json:"enabled"`
	Dumps         bool   `json:"dumps"`
	DumpsInPage   bool   `json:"dumpsInPage"`
	Deep          bool   `json:"deep"`
	SlowRequestMs int    `json:"slowRequestMs"`
	SlowQueryMs   int    `json:"slowQueryMs"`
	NPlusOne      int    `json:"nPlusOne"`
	Editor        string `json:"editor"`
}

// SettingsOf resolves a site's settings (an unset Watch = off).
func SettingsOf(s config.Site) Settings {
	out := Settings{SlowRequestMs: DefaultSlowRequestMs, SlowQueryMs: DefaultSlowQueryMs, NPlusOne: DefaultNPlusOne}
	w := s.Watch
	if w == nil {
		return out
	}
	out.Enabled, out.Dumps, out.DumpsInPage, out.Deep, out.Editor = w.Enabled, w.Dumps, w.DumpsInPage, w.Deep, w.Editor
	if w.SlowRequestMs > 0 {
		out.SlowRequestMs = w.SlowRequestMs
	}
	if w.SlowQueryMs > 0 {
		out.SlowQueryMs = w.SlowQueryMs
	}
	if w.NPlusOne > 1 {
		out.NPlusOne = w.NPlusOne
	}
	return out
}

// GatePath is the auto_prepend_file of watched sites.
func GatePath(p pmdir.Paths) string { return filepath.Join(p.WatchDir(), "mullion-watch.php") }

// IniDir holds mullion-watch.ini (auto_prepend_file = the gate) — added
// to PHP_INI_SCAN_DIR for a watched site's workers and commands, since
// the CLI doesn't get Caddy's PHP_VALUE.
func IniDir(p pmdir.Paths) string { return filepath.Join(p.WatchDir(), "ini") }

// iniPath writes a path for php.ini / PHP_VALUE: forward slashes (PHP
// accepts them everywhere, and a backslash inside an ini "…" string can
// read as an escape).
func iniPath(path string) string { return filepath.ToSlash(path) }

// PrependValue is the ini assignment that loads the gate.
func PrependValue(p pmdir.Paths) string {
	return `auto_prepend_file="` + iniPath(GatePath(p)) + `"`
}

// EnsureFiles writes the PHP prepend (gate + library) and the CLI ini
// when their content changed. They are never removed while Mullion is
// installed: php-fpm keeps a PHP_VALUE for the later requests its
// worker serves, so a missing file would break other sites.
func EnsureFiles(p pmdir.Paths) error {
	if err := os.MkdirAll(IniDir(p), 0o755); err != nil {
		return err
	}
	files := map[string][]byte{
		GatePath(p): gatePHP,
		filepath.Join(p.WatchDir(), "mullion-watch-lib.php"): libPHP,
		filepath.Join(IniDir(p), "mullion-watch.ini"):        []byte("; Generated by mullion — do not edit.\n" + PrependValue(p) + "\n"),
	}
	for path, data := range files {
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
			continue
		}
		tmp := path + ".tmp"
		if err := os.WriteFile(tmp, data, 0o644); err != nil {
			return err
		}
		if err := os.Rename(tmp, path); err != nil {
			os.Remove(tmp)
			return err
		}
	}
	return nil
}

// phpConfig is <site dir>/config.json — what the PHP side reads on
// every request (so a settings change needs no reload).
type phpConfig struct {
	Enabled     bool `json:"enabled"`
	Dumps       bool `json:"dumps"`
	DumpsInPage bool `json:"dumpsInPage"`
	Deep        bool `json:"deep"`
}

// WriteSiteConfig creates the site's watch folder and its config.json.
func WriteSiteConfig(p pmdir.Paths, s config.Site) error {
	dir := p.WatchSiteDir(s.Name)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	st := SettingsOf(s)
	data, _ := json.Marshal(phpConfig{Enabled: st.Enabled, Dumps: st.Dumps, DumpsInPage: st.DumpsInPage, Deep: st.Deep})
	tmp := filepath.Join(dir, "config.json.tmp")
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, filepath.Join(dir, "config.json"))
}

// CLIEnv returns the variables a watched site's artisan commands and
// queue workers need: MULLION_WATCH (the gate's switch) and
// PHP_INI_SCAN_DIR extended with IniDir. current is the existing
// PHP_INI_SCAN_DIR ("" = unset: a leading separator keeps PHP's
// compiled-in scan dir).
func CLIEnv(p pmdir.Paths, site, current string) map[string]string {
	scan := string(os.PathListSeparator) + IniDir(p)
	if current != "" {
		scan = current + string(os.PathListSeparator) + IniDir(p)
	}
	return map[string]string{
		"MULLION_WATCH":    p.WatchSiteDir(site),
		"PHP_INI_SCAN_DIR": scan,
	}
}

// EventsPath is the PHP side's current events file; RotatedPath the one
// before it (the PHP side renames past 20 MB, keeping one).
func EventsPath(p pmdir.Paths, site string) string {
	return filepath.Join(p.WatchSiteDir(site), "events.jsonl")
}
func RotatedPath(p pmdir.Paths, site string) string {
	return filepath.Join(p.WatchSiteDir(site), "events.1.jsonl")
}
