// Package caddy generates the Caddyfile and controls the Caddy process
// that serves every linked site.
package caddy

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// SiteConf is everything the Caddyfile needs to know about one site.
type SiteConf struct {
	Name      string // site name (the wake key for down dev servers)
	Host      string // e.g. "blog.test"
	Kind      string // "php" (default), "node", "static", or "proxy"
	Root      string // absolute document root (php and static sites)
	FcgiPort  int    // FastCGI port for this site's PHP version
	ProxyPort int    // dev-server port for node sites (0 = down); the upstream of "proxy" ones
	// RewriteHost makes the proxy send "localhost:<port>" as the Host
	// header — Vite-family dev servers block unknown hosts (and old
	// versions ignore the allow-list env var), but always accept
	// localhost. Only set for Vite and webpack-dev-server projects:
	// others (Next.js) rely on the original Host for origin checks.
	RewriteHost bool
	// AgentPort receives requests while the dev server is down: the
	// agent shows a "starting…" page and wakes the server, so opening
	// the link is all the user does.
	AgentPort int
	Secure    bool
	// Aliases are extra full hostnames the same block serves, e.g.
	// "api.blog.test" or the wildcard "*.blog.test". Every host keeps
	// its original Host header on the way to PHP, so framework
	// subdomain routing works; proxied node sites also get it in
	// X-Forwarded-Host (Caddy sets that by default).
	Aliases []string
	// Watch turns on the live watcher's PHP side for this site (php
	// sites only): Prepend is Mullion's auto_prepend_file, passed with
	// PHP_VALUE so only this site loads it, and Dir its events folder
	// (MULLION_WATCH, which the prepend checks — php-fpm keeps a
	// PHP_VALUE for later requests its worker serves, so another site
	// may run the prepend too, and must find it a no-op).
	Watch *WatchConf
	// Prod is production-like mode (the project page's Performance tab):
	// FastCGI params for PHP sites, long cache headers for fingerprinted
	// assets. nil = off.
	Prod *ProdConf
	// ValidateTimestamps, when "0" or "1", passes
	// opcache.validate_timestamps in PHP_VALUE (php sites). Production-
	// like mode freezes it ("0"); while any site does, every other PHP
	// site states its own value ("1"), because php-fpm keeps a
	// PHP_VALUE for the later requests its worker serves — another
	// site's "0" must not stick to this one.
	ValidateTimestamps string
	// FastCGIEnv are extra php_fastcgi env lines (name, value), e.g. the
	// profiler's PHP_ADMIN_VALUE. Values can contain newlines.
	FastCGIEnv [][2]string
}

// ProdConf is production-like mode as the Caddyfile needs it.
type ProdConf struct {
	// Env are FastCGI params for PHP (APP_ENV=production,
	// APP_DEBUG=false…): Laravel's env() reads $_SERVER before .env and
	// never lets .env overwrite them, so the project's files stay as
	// they are.
	Env map[string]string
}

// hashedAssets matches fingerprinted build files under the usual build
// folders (Vite's /build/assets/app-BkL3x9Qa.js and /assets/…,
// Next.js's /_next/static/…, Create React App's /static/js/main.3f2a9c1b.js):
// they never change under the same name, so they can be cached for a year.
const hashedAssets = `^/(?:build/assets|assets|_next/static|static/(?:js|css|media))/.*[.-][A-Za-z0-9_-]{8,}\.(?:js|mjs|css|woff2?|ttf|otf|png|jpe?g|gif|svg|webp|avif|ico|wasm)$`

// writeHashedCache renders the long-cache header for fingerprinted assets.
func writeHashedCache(b *strings.Builder) {
	b.WriteString("\t@hashed path_regexp " + quote(hashedAssets) + "\n")
	b.WriteString("\theader @hashed Cache-Control \"public, max-age=31536000, immutable\"\n")
}

// WatchConf is a site's watcher settings as the Caddyfile needs them.
type WatchConf struct {
	Prepend string
	Dir     string
	// RequestID tags each request with Caddy's per-request UUID — in the
	// access log (log_append, Caddy 2.8+) and for PHP (MULLION_RID) — so
	// a request row links to what PHP recorded for it.
	RequestID bool
}

// Generate renders the full Caddyfile. Secured sites use Caddy's internal
// CA (locally-trusted certificates); the rest are served over plain HTTP.
// GracePeriod is how long a reload (or stop) lets the old config's
// in-flight requests finish before closing them.
const GracePeriod = "10s"

func Generate(sites []SiteConf, logsDir string) string {
	var b strings.Builder
	b.WriteString("# Generated by mullion — do not edit; changes are overwritten.\n")
	// No skip_install_trust here: Caddy's Caddyfile adapter treats it as a
	// bare flag and ignores its argument, so `skip_install_trust false`
	// would actually DISABLE installing the root CA into the trust store.
	// grace_period: on a reload Caddy waits for the old config's
	// in-flight requests before it answers, and by default it waits
	// forever — one long-lived streaming response through a site (an
	// SSE feed, a long poll) would hang every `caddy reload`. Bound it.
	b.WriteString("{\n\tadmin 127.0.0.1:2019\n\tlocal_certs\n\tgrace_period " + GracePeriod + "\n}\n")

	for _, s := range sites {
		b.WriteString("\n" + siteAddresses(s) + " {\n")
		if s.Secure {
			b.WriteString("\ttls internal\n")
		}
		switch s.Kind {
		case "node":
			switch {
			case s.ProxyPort > 0 && s.RewriteHost:
				// localhost (not 127.0.0.1): dev servers often listen on
				// ::1 only, and dialing localhost covers both families.
				// keepalive off: pooled idle connections would look like
				// an open tab and keep the idle watcher from ever
				// sleeping the server — real tabs stay visible through
				// their live websocket.
				// max_conns_per_host 64: a Vite page's initial module
				// graph can fire hundreds of requests over HTTP/2 at
				// once; without keepalive, Caddy would dial that many
				// upstream connections simultaneously and overflow the
				// dev server's accept queue (macOS somaxconn=128),
				// causing "connection reset by peer" 502s. Capping
				// concurrent dials queues the rest instead of dropping
				// them.
				b.WriteString(fmt.Sprintf("\treverse_proxy localhost:%d {\n\t\theader_up Host {upstream_hostport}\n\t\ttransport http {\n\t\t\tkeepalive off\n\t\t\tmax_conns_per_host 64\n\t\t}\n\t}\n", s.ProxyPort))
			case s.ProxyPort > 0:
				b.WriteString(fmt.Sprintf("\treverse_proxy localhost:%d {\n\t\ttransport http {\n\t\t\tkeepalive off\n\t\t\tmax_conns_per_host 64\n\t\t}\n\t}\n", s.ProxyPort))
			case s.AgentPort > 0:
				// Dev server down: the agent wakes it and shows a
				// self-refreshing "starting…" page in the meantime.
				b.WriteString(fmt.Sprintf("\treverse_proxy 127.0.0.1:%d {\n\t\theader_up X-Mullion-Wake %q\n\t}\n", s.AgentPort, s.Name))
			default:
				b.WriteString("\trespond \"The dev server for this site is not running — run `mullion start` (or open the Mullion panel).\" 503\n")
			}
		case "proxy":
			// A local service's web UI (Mail's inbox). reverse_proxy
			// passes websocket upgrades through on its own; flush_interval
			// -1 streams responses (live updates) instead of buffering.
			b.WriteString(fmt.Sprintf("\treverse_proxy 127.0.0.1:%d {\n\t\tflush_interval -1\n\t}\n", s.ProxyPort))
		case "static":
			b.WriteString("\troot * " + quote(s.Root) + "\n")
			b.WriteString("\tencode zstd gzip\n")
			if s.Prod != nil {
				writeHashedCache(&b)
			}
			// Single-page apps route in the browser: unknown paths fall
			// back to index.html.
			b.WriteString("\ttry_files {path} /index.html\n")
			b.WriteString("\tfile_server\n")
		default: // php
			b.WriteString("\troot * " + quote(s.Root) + "\n")
			b.WriteString("\tencode zstd gzip\n")
			if s.Prod != nil {
				writeHashedCache(&b)
			}
			// PHP_VALUE is ini syntax, one directive per line (php-fpm
			// splits it on newlines); a path is quoted inside it.
			var ini []string
			if w := s.Watch; w != nil {
				ini = append(ini, `auto_prepend_file="`+w.Prepend+`"`)
			}
			if v := s.ValidateTimestamps; v == "0" || v == "1" {
				ini = append(ini, "opcache.validate_timestamps="+v)
			}
			var env []string
			if p := s.Prod; p != nil {
				keys := make([]string, 0, len(p.Env))
				for k := range p.Env {
					keys = append(keys, k)
				}
				sort.Strings(keys)
				for _, k := range keys {
					env = append(env, "\t\tenv "+k+" "+quote(p.Env[k])+"\n")
				}
			}
			w := s.Watch
			for _, e := range s.FastCGIEnv {
				env = append(env, "\t\tenv "+e[0]+" "+quote(e[1])+"\n")
			}
			if len(ini) == 0 && len(env) == 0 && w == nil {
				b.WriteString(fmt.Sprintf("\tphp_fastcgi 127.0.0.1:%d\n", s.FcgiPort))
			} else {
				b.WriteString(fmt.Sprintf("\tphp_fastcgi 127.0.0.1:%d {\n", s.FcgiPort))
				if len(ini) > 0 {
					b.WriteString("\t\tenv PHP_VALUE " + quote(strings.Join(ini, "\n")) + "\n")
				}
				if w != nil {
					b.WriteString("\t\tenv MULLION_WATCH " + quote(w.Dir) + "\n")
					if w.RequestID {
						b.WriteString("\t\tenv MULLION_RID {http.request.uuid}\n")
					}
				}
				for _, e := range env {
					b.WriteString(e)
				}
				b.WriteString("\t}\n")
				if w != nil && w.RequestID {
					b.WriteString("\tlog_append mullion_rid {http.request.uuid}\n")
				}
			}
			b.WriteString("\tfile_server\n")
		}
		b.WriteString("\tlog {\n\t\toutput file " + quote(filepath.Join(logsDir, s.Host+".log")) + "\n\t}\n")
		b.WriteString("}\n")
	}
	return b.String()
}

// siteAddresses is the block's address list: the site's host plus its
// aliases, each forced to plain HTTP unless the site is secured (with
// `tls internal`, a "*.blog.test" address gets a wildcard certificate
// from Caddy's local CA).
func siteAddresses(s SiteConf) string {
	hosts := append([]string{s.Host}, s.Aliases...)
	addrs := make([]string, 0, len(hosts))
	for _, h := range hosts {
		if s.Secure {
			addrs = append(addrs, h)
		} else {
			addrs = append(addrs, "http://"+h)
		}
	}
	return strings.Join(addrs, ", ")
}

// DocRoot picks the directory Caddy should serve for a project: public/
// when it contains an index.php (Laravel & friends), else the project root.
func DocRoot(projectPath string) string {
	public := filepath.Join(projectPath, "public")
	if _, err := os.Stat(filepath.Join(public, "index.php")); err == nil {
		return public
	}
	return projectPath
}

// quote wraps a path in a Caddyfile string. Caddy's lexer only treats \"
// as an escape and keeps every other backslash as is, so Windows paths go
// in unchanged: doubling them gave Caddy C:\\Mullion\\logs, which no
// longer matched the logs dir ServingOurs looks for. A trailing backslash
// (a drive root) is doubled so it can't escape the closing quote.
func quote(s string) string {
	s = strings.ReplaceAll(s, `"`, `\"`)
	if strings.HasSuffix(s, `\`) {
		s += `\`
	}
	return `"` + s + `"`
}
