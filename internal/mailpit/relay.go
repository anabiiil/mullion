package mailpit

// The optional "release to a real inbox" relay. Off by default: Mailpit
// only gets --smtp-relay-config when the user saved an enabled relay,
// and even then a captured message goes out only when it is released by
// hand (Mullion never passes --smtp-relay-all / --smtp-relay-matching).
//
// The settings live in relay.json (Mullion's copy, read back by the
// panel) and are rendered to relay.yaml (Mailpit's format: see
// SMTPRelayConfigStruct in mailpit's config/config.go). Both hold the
// SMTP password, so both are written 0600.

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"pm/internal/pmdir"
)

// RelayConfig is the real SMTP server released messages go through.
type RelayConfig struct {
	Enabled  bool   `json:"enabled"`
	Host     string `json:"host"`
	Port     int    `json:"port"`
	Username string `json:"username,omitempty"`
	Password string `json:"password,omitempty"`
	// Security is "starttls" (port 587), "tls" (implicit TLS, port 465)
	// or "none".
	Security string `json:"security"`
	// AllowedRecipients is a regular expression a release recipient must
	// match ("" = any) — a guard against releasing to a real customer.
	AllowedRecipients string `json:"allowedRecipients,omitempty"`
}

func relayJSON(paths pmdir.Paths) string { return filepath.Join(BaseDir(paths), "relay.json") }

// RelayYAML is the config file handed to Mailpit.
func RelayYAML(paths pmdir.Paths) string { return filepath.Join(BaseDir(paths), "relay.yaml") }

// LoadRelay reads the saved relay settings (zero value when none).
func LoadRelay(paths pmdir.Paths) RelayConfig {
	var c RelayConfig
	if b, err := os.ReadFile(relayJSON(paths)); err == nil {
		_ = json.Unmarshal(b, &c)
	}
	return c
}

var hostRe = regexp.MustCompile(`^[A-Za-z0-9.\-]+$|^\[[0-9A-Fa-f:.]+\]$`)

// Validate checks an enabled relay's settings.
func (c RelayConfig) Validate() error {
	if !c.Enabled {
		return nil
	}
	if !hostRe.MatchString(c.Host) {
		return fmt.Errorf("invalid SMTP host %q", c.Host)
	}
	if c.Port < 1 || c.Port > 65535 {
		return fmt.Errorf("invalid SMTP port %d", c.Port)
	}
	switch c.Security {
	case "starttls", "tls", "none":
	default:
		return fmt.Errorf("security must be starttls, tls or none (got %q)", c.Security)
	}
	if c.AllowedRecipients != "" {
		if _, err := regexp.Compile(c.AllowedRecipients); err != nil {
			return fmt.Errorf("allowed recipients is not a valid regular expression: %v", err)
		}
	}
	if strings.ContainsAny(c.Username+c.Password, "\x00\r\n") {
		return errors.New("the username and password must be a single line")
	}
	return nil
}

// yamlString renders a YAML double-quoted scalar (a JSON string is one).
func yamlString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

// RenderRelayYAML renders Mailpit's relay config file.
func RenderRelayYAML(c RelayConfig) string {
	auth := "none"
	if c.Username != "" {
		auth = "plain"
	}
	lines := []string{
		"# Generated by mullion — do not edit; set the relay on the Mail page.",
		"host: " + yamlString(c.Host),
		"port: " + strconv.Itoa(c.Port),
		"starttls: " + strconv.FormatBool(c.Security == "starttls"),
		"tls: " + strconv.FormatBool(c.Security == "tls"),
		"auth: " + auth,
	}
	if c.Username != "" {
		lines = append(lines, "username: "+yamlString(c.Username), "password: "+yamlString(c.Password))
		if c.Security == "none" {
			// Mailpit refuses a PLAIN login over an unencrypted
			// connection unless told the server is trusted.
			lines = append(lines, "allow-insecure: true")
		}
	}
	if c.AllowedRecipients != "" {
		lines = append(lines, "allowed-recipients: "+yamlString(c.AllowedRecipients))
	}
	return strings.Join(lines, "\n") + "\n"
}

// SaveRelay stores the relay settings (an empty Password keeps the saved
// one, so the panel never has to send it back) and writes or removes
// relay.yaml. A running Mailpit picks the change up only on restart.
func SaveRelay(paths pmdir.Paths, c RelayConfig) error {
	c.Host = strings.TrimSpace(c.Host)
	if c.Password == "" {
		c.Password = LoadRelay(paths).Password
	}
	if err := c.Validate(); err != nil {
		return err
	}
	if err := os.MkdirAll(BaseDir(paths), 0o755); err != nil {
		return err
	}
	b, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return err
	}
	if err := writePrivate(relayJSON(paths), b); err != nil {
		return err
	}
	if !c.Enabled {
		if err := os.Remove(RelayYAML(paths)); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	return writePrivate(RelayYAML(paths), []byte(RenderRelayYAML(c)))
}

// writePrivate writes a file only its owner can read (0600), tightening
// an existing file's mode too.
func writePrivate(path string, data []byte) error {
	if err := os.WriteFile(path, data, 0o600); err != nil {
		return err
	}
	return os.Chmod(path, 0o600)
}

// relayArgs adds the relay config to Mailpit's command line when one is
// enabled.
func relayArgs(paths pmdir.Paths) []string {
	if _, err := os.Stat(RelayYAML(paths)); err != nil {
		return nil
	}
	return []string{"--smtp-relay-config", RelayYAML(paths)}
}
