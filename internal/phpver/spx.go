package phpver

// SPX (github.com/NoiseByNorthwest/php-spx) is the profiler behind the
// project page's Performance → Profiler tab and `mullion profile`. It is
// GPLv3, so mullion never ships a binary of it: EnsureSpx builds spx.so
// on the user's own machine from the pinned, checksum-verified release
// tarball, against the matching php.net sources (the same no-phpize
// approach as ldap/pdo_dblib, see spx_darwin.go).
//
// Platforms: macOS only for now. SPX supports Linux, macOS and FreeBSD;
// its tree has a few win32 sources but no config.w32 and no Windows
// release assets, and neither windows.php.net's PECL mirror nor SPX's
// releases carry a DLL. Excimer (the other stack-sampling profiler) has
// no Windows build either. xhprof has PECL DLLs, but it records only
// caller/callee pairs — no full stacks, so no honest flame graph.
//
// Loading: spx.so goes into the version's php.ini (extension=…) with
// SPX's defaults, which leave it fully disabled — SPX's own docs: "when
// disabled there is no performance impact". Everything that turns it
// on (spx.http_enabled, the key, the data dir…) is per site, passed by
// Caddy with PHP_ADMIN_VALUE (see internal/profiler).

import (
	"os"
	"path/filepath"
	"strings"

	"pm/internal/pmdir"
)

const (
	// SpxVersion is the SPX release mullion builds.
	SpxVersion = "0.4.22"
	spxURL     = "https://github.com/NoiseByNorthwest/php-spx/archive/refs/tags/v" + SpxVersion + ".tar.gz"
	spxSHA256  = "6f89addd100d3d71168c094612eb8e1c06fd8062da6ee4d9df5b31bdfc4de160"
)

// spxIniComment heads the php.ini line EnsureSpx adds. It must not
// contain "=" (parseExtLine would read it as a directive).
const spxIniComment = "SPX " + SpxVersion + " profiler (mullion profile) — built on this Mac against php.net sources; GPLv3, github.com/NoiseByNorthwest/php-spx"

// SpxSoPath is where a version's spx.so lives.
func SpxSoPath(paths pmdir.Paths, version string) string {
	return filepath.Join(paths.PhpVersionDir(version), "ext", "spx.so")
}

// SpxAssetsDir is SPX's web UI (its control panel and report viewer),
// shared by every PHP version; its path is compiled into spx.so as the
// default spx.http_ui_assets_dir.
func SpxAssetsDir(paths pmdir.Paths) string {
	return filepath.Join(paths.Home, "lib", "spx-"+SpxVersion, "web-ui")
}

// SpxLoaded reports, read-only, whether the version has spx.so built and
// an active extension= line for it in its php.ini.
func SpxLoaded(paths pmdir.Paths, version string) bool {
	if !fileExists(SpxSoPath(paths, version)) {
		return false
	}
	data, err := os.ReadFile(filepath.Join(paths.PhpVersionDir(version), "php.ini"))
	if err != nil {
		return false
	}
	return iniLoadsModule(string(data), "spx")
}

// iniLoadsModule reports whether php.ini text has an active extension=
// line for module.
func iniLoadsModule(ini, module string) bool {
	for _, line := range strings.Split(ini, "\n") {
		if name, active, _ := parseExtLine(line); active && name == module {
			return true
		}
	}
	return false
}

// spxWanted reports whether another installed patch of version's branch
// loads SPX — then a fresh install of version (`mullion php update`)
// builds it too, so the carried-over php.ini line finds its module.
func spxWanted(paths pmdir.Paths, version string) bool {
	sel, err := ParseSelector(version)
	if err != nil {
		return false
	}
	installed, err := Installed(paths)
	if err != nil {
		return false
	}
	for _, v := range installed {
		if v == version {
			continue
		}
		s, err := ParseSelector(v)
		if err != nil || s.Major != sel.Major || s.Minor != sel.Minor {
			continue
		}
		if SpxLoaded(paths, v) {
			return true
		}
	}
	return false
}

// spxSources are SPX's C files, as its config.m4 lists them.
var spxSources = []string{
	"php_spx.c", "spx_profiler.c", "spx_profiler_tracer.c", "spx_profiler_sampler.c",
	"spx_reporter_full.c", "spx_reporter_fp.c", "spx_reporter_trace.c", "spx_metric.c",
	"spx_resource_stats.c", "spx_hmap.c", "spx_str_builder.c", "spx_output_stream.c",
	"spx_php.c", "spx_stdio.c", "spx_config.c", "spx_utils.c", "spx_fmt.c",
}

// spxConfigH is the config.h phpize would generate for SPX: php_spx.h
// includes it under HAVE_CONFIG_H.
func spxConfigH(assetsDir string) string {
	return "/* Generated by mullion (what phpize's configure would write for SPX). */\n" +
		"#define HAVE_SPX 1\n" +
		"#define SPX_HTTP_UI_ASSETS_DIR \"" + strings.ReplaceAll(assetsDir, `"`, `\"`) + "\"\n"
}

// spxClangArgs is the single clang invocation that compiles and links
// spx.so — what phpize + SPX's config.m4 + make amount to: SPX's own
// CFLAGS (minus -Werror, so a newer compiler's warning can't fail the
// build), the configured php-src tree's include dirs (phpSrc has run
// ./configure, so main/php_config.h matches the static build: NTS, no
// debug), and a bundle that resolves PHP's symbols from the php binary
// loading it (-undefined dynamic_lookup), linked against the SDK's zlib.
func spxClangArgs(phpSrc, spxSrc, configDir, sdk, out string) []string {
	args := []string{
		"-O3", "-pthread", "-std=gnu90", "-Wall", "-Wno-typedef-redefinition", "-fPIC",
		"-DHAVE_CONFIG_H", "-DCOMPILE_DL_SPX=1", "-DZEND_COMPILE_DL_EXT=1",
		"-I" + configDir,
		"-I" + phpSrc,
		"-I" + filepath.Join(phpSrc, "main"),
		"-I" + filepath.Join(phpSrc, "Zend"),
		"-I" + filepath.Join(phpSrc, "TSRM"),
		"-I" + filepath.Join(phpSrc, "ext"),
		"-I" + filepath.Join(phpSrc, "ext", "date", "lib"),
	}
	if sdk != "" {
		args = append(args, "-isysroot", sdk)
	}
	args = append(args, "-bundle", "-undefined", "dynamic_lookup", "-o", out)
	for _, f := range spxSources {
		args = append(args, filepath.Join(spxSrc, "src", f))
	}
	return append(args, "-lz")
}
